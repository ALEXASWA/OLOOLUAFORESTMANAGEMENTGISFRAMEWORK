import csv
import json
from collections import defaultdict
from pathlib import Path

from django.core.management.base import BaseCommand, CommandError
from django.db import transaction

from apps.forests.models import Forest
from apps.gis_layers.models import RasterLayer
from apps.ecology.models import Indicator, IndicatorProduct
from apps.lulc.models import LULCClass, LULCMap, LULCStatistic, LULCTransition
from apps.management.models import ManagementZoneStatistic


CLASS_NAMES = {1: "Forest", 2: "Grassland", 3: "Quarry", 4: "Built-up"}
YEARS = (1990, 2000, 2010, 2020, 2025)


class Command(BaseCommand):
    help = "Import real Google Earth Engine LULC tables and raster references idempotently."

    def add_arguments(self, parser):
        parser.add_argument("--forest", default="oloolua")
        parser.add_argument("--root", required=True, help="EOILOLOOLUA export directory.")

    def handle(self, *args, **options):
        forest = Forest.objects.filter(code=options["forest"]).first()
        if not forest:
            raise CommandError(f"Forest code not found: {options['forest']}")
        root = Path(options["root"])
        tables = root / "PROFESSIONAL_TABLES"
        area_path = tables / "LULC_Area_Statistics_Clean.csv"
        transition_path = tables / "LULC_Transitions_Clean.csv"
        if not area_path.exists():
            raise CommandError(f"Missing GEE LULC table: {area_path}")

        with transaction.atomic():
            classes = self._ensure_classes(forest)
            self._import_area_tables(forest, root, area_path, classes)
            if transition_path.exists():
                self._import_transitions(forest, transition_path, classes)
            self._import_indicator_tables(forest, tables)
            self._import_management_zone_statistics(forest, tables)
            self._register_rasters(forest, root)

        self.stdout.write(self.style.SUCCESS("Imported real GEE LULC statistics, transitions, and raster references."))

    def _ensure_classes(self, forest):
        classes = {}
        for code, name in CLASS_NAMES.items():
            classes[code], _ = LULCClass.objects.get_or_create(
                forest=forest, code=code, defaults={"name": name, "display_order": code}
            )
        return classes

    def _import_area_tables(self, forest, root, path, classes):
        rows = list(csv.DictReader(path.open(encoding="utf-8-sig", newline="")))
        grouped = defaultdict(list)
        for row in rows:
            if row.get("Zone", "Oloolua") != "Oloolua":
                continue
            grouped[int(row["Year"])].append(row)

        for year, year_rows in grouped.items():
            raster_path = root / f"Oloolua_LULC_{year}.tif"
            raster, _ = RasterLayer.objects.update_or_create(
                forest=forest,
                slug=f"oloolua-lulc-{year}",
                version="gee-v1",
                defaults={
                    "name": f"Oloolua LULC {year}",
                    "kind": "lulc",
                    "year": year,
                    "file_path": str(raster_path),
                    "source": "Google Earth Engine export",
                    "crs": "EPSG:32737",
                    "resolution_m": 10 if year == 2025 else 30,
                    "processing_method": "Supplied Oloolua GEE Random Forest workflow",
                    "description": "Real exported classified LULC raster; not regenerated by FM-GDSS.",
                    "active": raster_path.exists(),
                },
            )
            lulc_map, _ = LULCMap.objects.update_or_create(
                forest=forest, year=year, version="gee-v1",
                defaults={
                    "raster": raster,
                    "source": str(path),
                    "resolution_m": 10 if year == 2025 else 30,
                    "classification_method": "Google Earth Engine Random Forest",
                    "notes": "Historical Landsat or 2025 Sentinel-2 classification from supplied workflow.",
                },
            )
            total = sum(float(row["Area_ha"]) for row in year_rows)
            for row in year_rows:
                code = int(row["Class"])
                LULCStatistic.objects.update_or_create(
                    lulc_map=lulc_map,
                    lulc_class=classes[code],
                    defaults={
                        "area_ha": float(row["Area_ha"]),
                        "percentage": float(row.get("Percentage") or (float(row["Area_ha"]) / total * 100 if total else 0)),
                    },
                )

    def _import_transitions(self, forest, path, classes):
        for row in csv.DictReader(path.open(encoding="utf-8-sig", newline="")):
            if row.get("Zone", "Oloolua") != "Oloolua":
                continue
            from_class = classes[int(float(row["From"]))]
            to_class = classes[int(float(row["To"]))]
            LULCTransition.objects.update_or_create(
                forest=forest,
                from_year=int(row["FromYear"]),
                to_year=int(row["ToYear"]),
                from_class=from_class,
                to_class=to_class,
                defaults={"area_ha": float(row["Area_ha"]), "percentage": 0},
            )

    def _import_indicator_tables(self, forest, tables):
        table_specs = {
            "Forest_Change_Areas.csv": ("Forest change", "derived"),
            "BuiltUp_Quarry_Expansion_Areas.csv": ("Remote-sensing anthropogenic pressure proxy", "derived"),
            "Forest_Edge_Core_Areas.csv": ("Forest edge and core structure", "derived"),
            "NDVI_2025_Descriptive_Statistics.csv": ("NDVI vegetation condition", "derived"),
            "Management_Index_Summary.csv": ("Management indices", "proposed"),
            "Management_Zone_Areas.csv": ("Proposed analytical management zones", "proposed"),
        }
        for filename, (name, status) in table_specs.items():
            path = tables / filename
            if not path.exists():
                continue
            rows = list(csv.DictReader(path.open(encoding="utf-8-sig", newline="")))
            indicator, _ = Indicator.objects.update_or_create(
                forest=forest,
                slug=self._slug(name),
                defaults={
                    "name": name,
                    "status": status,
                    "unit": "ha" if "Area" in filename else "index/value",
                    "description": "Imported directly from supplied Google Earth Engine analysis output.",
                },
            )
            IndicatorProduct.objects.update_or_create(
                indicator=indicator,
                year=2025,
                version="gee-v1",
                defaults={
                    "value_summary": {"source_file": str(path), "rows": rows},
                    "processing_method": "Supplied Oloolua GEE workflow output; no values regenerated by FM-GDSS.",
                    "source": str(path),
                },
            )

    def _register_rasters(self, forest, root):
        raster_specs = {
            "Oloolua_LULC_": "lulc",
            "Oloolua_Forest_": "ecology",
            "Oloolua_Human_Pressure": "threat",
            "Oloolua_Conservation_Priority": "management",
            "Oloolua_Rehabilitation_Priority": "management",
            "Oloolua_Management_Zones": "management",
        }
        for path in root.glob("*.tif"):
            kind = next((kind for prefix, kind in raster_specs.items() if path.name.startswith(prefix)), None)
            if not kind:
                continue
            slug = path.stem.lower().replace("_", "-")
            existing = RasterLayer.objects.filter(forest=forest, slug=slug, version="gee-v1").first()
            if existing and existing.checksum:
                # Full metadata and colormaps are owned by ingest_gee_rasters;
                # do not clobber them with catalogue-only defaults here.
                continue
            year = next((int(token) for token in path.stem.split("_") if token.isdigit() and len(token) == 4), None)
            RasterLayer.objects.update_or_create(
                forest=forest, slug=slug, version="gee-v1",
                defaults={
                    "name": path.stem.replace("_", " "),
                    "kind": kind,
                    "year": year,
                    "file_path": str(path),
                    "source": "Google Earth Engine export",
                    "crs": "EPSG:32737",
                    "resolution_m": 10 if year == 2025 and kind == "lulc" else 30,
                    "processing_method": "Supplied Oloolua Sustainable Forest Ecosystem Analysis",
                    "description": "Real exported GeoTIFF referenced by FM-GDSS; not recreated or fabricated.",
                    "active": True,
                },
            )

    def _import_management_zone_statistics(self, forest, tables):
        path = tables / "Management_Zone_Areas.csv"
        if not path.exists():
            return
        for row in csv.DictReader(path.open(encoding="utf-8-sig", newline="")):
            code = str(row.get("Zone", "")).strip()
            name = str(row.get("Zone_Name", code)).strip()
            if not code:
                continue
            ManagementZoneStatistic.objects.update_or_create(
                forest=forest,
                zone_code=code,
                version="gee-v1",
                defaults={
                    "zone_name": name,
                    "area_ha": float(row.get("Area_ha") or 0),
                    "percentage": float(row.get("Percent") or 0),
                    "source": str(path),
                },
            )

    def _slug(self, value):
        return "-".join(value.lower().split())
